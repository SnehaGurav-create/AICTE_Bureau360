export function exportComplaintsToCSV(cases = COMPLAINT_CASES) {
  if (!cases || cases.length === 0) return;

  const headers = [
    'Case ID',
    'Title',
    'Institution Name',
    'AICTE PID',
    'District',
    'State',
    'Category',
    'Assigned Bureau',
    'Priority',
    'Status',
    'Ageing Days',
    'Received Date',
    'Last Updated',
    'Intake Source',
  ];

  const escapeCSV = (field) => {
    if (field === null || field === undefined) return '""';
    const str = String(field).replace(/"/g, '""');
    return `"${str}"`;
  };

  const rows = cases.map((c) => [
    escapeCSV(c.id),
    escapeCSV(c.title),
    escapeCSV(c.institutionName),
    escapeCSV(c.institutionId),
    escapeCSV(c.district),
    escapeCSV(c.state),
    escapeCSV(c.category),
    escapeCSV(c.assignedBureau),
    escapeCSV(c.priority),
    escapeCSV(c.status),
    escapeCSV(c.ageingDays),
    escapeCSV(c.receivedDate),
    escapeCSV(c.lastUpdatedDate),
    escapeCSV(c.source),
  ]);

  const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `AICTE_Bureau360_Complaints_Report_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}


/**
 * Retrieves an institution record by AICTE Permanent ID or name.
 * @param {string} instId - AICTE Permanent ID or institution name
 * @returns {Object|null}
 */
export function getInstitutionById(instId) {
  if (!instId) return null;
  const q = String(instId).trim().toLowerCase();
  return INSTITUTIONS.find((i) => i.id.toLowerCase() === q || i.name.toLowerCase() === q) || null;
}

